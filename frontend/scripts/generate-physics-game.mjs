const levels = [];
for (let i = 0; i < 100; i++) {
  const src = POOL[i % POOL.length];
  const [character, speech, question, , tag, opts, correct] = src;
  levels.push({
    id: i + 1,
    character,
    speech,
    question,
    icon: icons[i % icons.length],
    tag,
    options: opts.map((text, idx) => ({
      id: idx + 1,
      text: `${idx + 1}) ${text}`,
      isCorrect: idx === correct,
    })),
  });
}

